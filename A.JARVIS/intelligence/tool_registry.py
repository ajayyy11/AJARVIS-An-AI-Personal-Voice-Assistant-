"""Controlled allow-list for tools available to the AJARVIS agent layer.

Handlers are registered by application code, receive the authenticated username,
and never derive Python function names or shell commands from model output.
The confirmation flag must come from a trusted UI or application flow, never
from arguments generated by an AI model.
"""

from __future__ import annotations

from copy import deepcopy
from dataclasses import dataclass
import re
from threading import RLock
from typing import Any, Callable, Mapping


_TOOL_NAME = re.compile(r"^[a-z][a-z0-9_]{1,63}$")
_ALLOWED_RISKS = {"read_only", "reversible", "destructive"}
_ALLOWED_TYPES = {"string", "integer", "number", "boolean", "object", "array"}


class ToolRegistryError(ValueError):
    """Base exception for invalid tool registration or execution."""


class ToolNotFoundError(ToolRegistryError):
    """Raised when a tool is unregistered or disabled."""


class ToolArgumentError(ToolRegistryError):
    """Raised when arguments do not match a registered schema."""


class ToolConfirmationRequired(ToolRegistryError):
    """Raised when a tool needs explicit trusted confirmation."""


@dataclass(frozen=True)
class ToolSpec:
    """Tool metadata and its JSON-Schema-style argument contract."""

    name: str
    description: str
    handler: Callable[..., Any]
    parameters: Mapping[str, Any]
    risk_level: str = "read_only"
    requires_confirmation: bool = False
    enabled: bool = True

    @property
    def confirmation_required(self) -> bool:
        return self.requires_confirmation or self.risk_level == "destructive"

    def function_declaration(self) -> dict[str, Any]:
        """Provider-neutral declaration; excludes local Python handler."""
        return {
            "name": self.name,
            "description": self.description,
            "parameters": deepcopy(dict(self.parameters)),
        }

    def public_metadata(self) -> dict[str, Any]:
        return {
            "name": self.name,
            "description": self.description,
            "parameters": deepcopy(dict(self.parameters)),
            "risk_level": self.risk_level,
            "requires_confirmation": self.confirmation_required,
            "enabled": self.enabled,
        }


class ToolRegistry:
    """Thread-safe registry of explicitly approved application capabilities."""

    def __init__(self) -> None:
        self._tools: dict[str, ToolSpec] = {}
        self._lock = RLock()

    def register(
        self,
        name: str,
        description: str,
        handler: Callable[..., Any],
        *,
        parameters: Mapping[str, Any] | None = None,
        risk_level: str = "read_only",
        requires_confirmation: bool = False,
        enabled: bool = True,
    ) -> ToolSpec:
        if not isinstance(name, str) or not _TOOL_NAME.fullmatch(name):
            raise ToolRegistryError(
                "Tool names must be 2-64 characters, start with a lowercase "
                "letter, and contain only lowercase letters, digits, or underscores."
            )
        if not isinstance(description, str) or not description.strip():
            raise ToolRegistryError("Tool description must not be empty.")
        if not callable(handler):
            raise ToolRegistryError("Tool handler must be callable.")
        if not isinstance(risk_level, str) or risk_level not in _ALLOWED_RISKS:
            raise ToolRegistryError(
                f"risk_level must be one of: {', '.join(sorted(_ALLOWED_RISKS))}."
            )
        if not isinstance(requires_confirmation, bool) or not isinstance(enabled, bool):
            raise ToolRegistryError("Confirmation and enabled flags must be booleans.")

        if parameters is not None and not isinstance(parameters, Mapping):
            raise ToolRegistryError("Tool parameters must be an object schema.")
        schema = deepcopy(dict(parameters) if parameters is not None else {
            "type": "object",
            "properties": {},
            "required": [],
            "additionalProperties": False,
        })
        self._validate_schema(schema)
        spec = ToolSpec(
            name=name,
            description=description.strip(),
            handler=handler,
            parameters=schema,
            risk_level=risk_level,
            requires_confirmation=requires_confirmation,
            enabled=enabled,
        )
        with self._lock:
            if name in self._tools:
                raise ToolRegistryError(f"Tool '{name}' is already registered.")
            self._tools[name] = spec
        return spec

    def get(self, name: str) -> ToolSpec:
        with self._lock:
            registered = self._tools.get(name)
        if registered is None or not registered.enabled:
            raise ToolNotFoundError(f"Tool '{name}' is not available.")
        # Do not expose the registry's nested schema objects to external mutation.
        return ToolSpec(
            name=registered.name,
            description=registered.description,
            handler=registered.handler,
            parameters=deepcopy(dict(registered.parameters)),
            risk_level=registered.risk_level,
            requires_confirmation=registered.requires_confirmation,
            enabled=registered.enabled,
        )

    def list_tools(self, *, include_disabled: bool = False) -> list[dict[str, Any]]:
        with self._lock:
            specs = list(self._tools.values())
        return [
            spec.public_metadata()
            for spec in sorted(specs, key=lambda item: item.name)
            if include_disabled or spec.enabled
        ]

    def function_declarations(self) -> list[dict[str, Any]]:
        """List enabled declarations while keeping execution code local."""
        with self._lock:
            specs = list(self._tools.values())
        return [
            spec.function_declaration()
            for spec in sorted(specs, key=lambda item: item.name)
            if spec.enabled
        ]

    def invoke(
        self,
        name: str,
        *,
        username: str,
        arguments: Mapping[str, Any] | None = None,
        confirmed: bool = False,
    ) -> Any:
        """Invoke an allow-listed handler on behalf of an authenticated user."""
        if not isinstance(username, str) or not username.strip():
            raise ToolArgumentError("An authenticated username is required.")
        if not isinstance(confirmed, bool):
            raise ToolArgumentError("The confirmation flag must be a boolean.")

        spec = self.get(name)
        if spec.confirmation_required and not confirmed:
            raise ToolConfirmationRequired(
                f"Tool '{name}' requires explicit user confirmation."
            )
        if arguments is None:
            arguments = {}
        if not isinstance(arguments, Mapping):
            raise ToolArgumentError("Tool arguments must be an object.")

        normalized = dict(arguments)
        self._validate_arguments(spec.parameters, normalized)
        return spec.handler(username=username.strip(), **normalized)

    @classmethod
    def _validate_schema(cls, schema: Mapping[str, Any]) -> None:
        if not isinstance(schema, Mapping) or schema.get("type") != "object":
            raise ToolRegistryError("Tool parameter schema must have type 'object'.")
        properties = schema.get("properties", {})
        required = schema.get("required", [])
        if not isinstance(properties, Mapping):
            raise ToolRegistryError("Schema properties must be an object.")
        if not isinstance(required, list) or any(not isinstance(key, str) for key in required):
            raise ToolRegistryError("Schema required must be a list of property names.")
        if any(key not in properties for key in required):
            raise ToolRegistryError("Every required field must be declared in properties.")
        if "additionalProperties" in schema and not isinstance(schema["additionalProperties"], bool):
            raise ToolRegistryError("Schema additionalProperties must be a boolean.")

        for key, property_schema in properties.items():
            if not isinstance(key, str) or not key:
                raise ToolRegistryError("Schema property names must be non-empty strings.")
            if not isinstance(property_schema, Mapping):
                raise ToolRegistryError(f"Schema for '{key}' must be an object.")
            value_type = property_schema.get("type")
            if not isinstance(value_type, str) or value_type not in _ALLOWED_TYPES:
                raise ToolRegistryError(f"Schema for '{key}' uses an unsupported type.")
            if "enum" in property_schema and not isinstance(property_schema["enum"], list):
                raise ToolRegistryError(f"Schema enum for '{key}' must be a list.")

    @classmethod
    def _validate_arguments(
        cls,
        schema: Mapping[str, Any],
        arguments: Mapping[str, Any],
    ) -> None:
        properties = schema.get("properties", {})
        missing = [key for key in schema.get("required", []) if key not in arguments]
        if missing:
            raise ToolArgumentError(f"Missing required argument(s): {', '.join(missing)}.")

        unknown = [key for key in arguments if key not in properties]
        if unknown and not schema.get("additionalProperties", False):
            raise ToolArgumentError(f"Unknown argument(s): {', '.join(sorted(unknown))}.")

        for key, value in arguments.items():
            property_schema = properties.get(key)
            if property_schema is not None:
                cls._validate_value(key, value, property_schema)

    @classmethod
    def _validate_value(
        cls,
        name: str,
        value: Any,
        schema: Mapping[str, Any],
    ) -> None:
        value_type = schema["type"]
        valid = {
            "string": lambda item: isinstance(item, str),
            "integer": lambda item: isinstance(item, int) and not isinstance(item, bool),
            "number": lambda item: isinstance(item, (int, float)) and not isinstance(item, bool),
            "boolean": lambda item: isinstance(item, bool),
            "object": lambda item: isinstance(item, Mapping),
            "array": lambda item: isinstance(item, list),
        }[value_type](value)
        if not valid:
            raise ToolArgumentError(f"Argument '{name}' must be of type {value_type}.")
        if "enum" in schema and value not in schema["enum"]:
            raise ToolArgumentError(f"Argument '{name}' has an unsupported value.")
        if value_type == "string":
            if "minLength" in schema and len(value) < schema["minLength"]:
                raise ToolArgumentError(f"Argument '{name}' is too short.")
            if "maxLength" in schema and len(value) > schema["maxLength"]:
                raise ToolArgumentError(f"Argument '{name}' is too long.")
        if value_type in {"integer", "number"}:
            if "minimum" in schema and value < schema["minimum"]:
                raise ToolArgumentError(f"Argument '{name}' is below the allowed minimum.")
            if "maximum" in schema and value > schema["maximum"]:
                raise ToolArgumentError(f"Argument '{name}' exceeds the allowed maximum.")
